#!/usr/bin/env bash
# Nyxuri kitty theme hook — vendored from Noctalia 5.2.1 (MIT), brand-adapted.
# Manages the include line in kitty.conf; the theme file itself is written by
# the TemplateService render step before this hook runs.
set -euo pipefail

kitty_config_dir="${XDG_CONFIG_HOME:-$HOME/.config}/kitty"
config_file="$kitty_config_dir/kitty.conf"
theme_file="$kitty_config_dir/themes/nyxuri.conf"
include_line='include themes/nyxuri.conf'

mkdir -p "$kitty_config_dir"
touch "$config_file"

tmp_file="$(mktemp "${config_file}.tmp.XXXXXX")"

cleanup() {
    rm -f "$tmp_file"
}
trap cleanup EXIT

awk -v include_line="$include_line" '
    BEGIN {
        placed = 0
        include_seen = 0
    }

    # Remove the block generated by `kitty +kitten themes`.
    /^# BEGIN_KITTY_THEME[[:space:]]*$/ {
        in_theme_block = 1
        next
    }

    in_theme_block && /^# END_KITTY_THEME[[:space:]]*$/ {
        in_theme_block = 0
        next
    }

    in_theme_block {
        next
    }

    # Strip legacy Noctalia theme includes or bare current-theme.conf symlink
    # to avoid overriding Nyxuri Shell colors when dual shells co-exist.
    $0 ~ /^include[[:space:]]+(themes\/noctalia\.conf|current-theme\.conf)$/ {
        next
    }

    # Preserve the first existing nyxuri include if already encountered before __custom__.conf.
    # Remove any duplicate copies.
    $0 == include_line {
        if (!include_seen) {
            include_seen = 1
            placed = 1
            print
        }
        next
    }

    # Guarantee include_line is placed BEFORE user custom configurations (__custom__.conf)
    # so that user-defined overrides in __custom__.conf take precedence over dynamic themes.
    $0 ~ /^include[[:space:]]+__custom__\.conf$/ {
        if (!placed) {
            print include_line
            placed = 1
            include_seen = 1
        }
        print
        next
    }

    {
        print
    }

    END {
        # Add the include if it was not already placed.
        if (!placed) {
            print include_line
        }
    }
' "$config_file" >"$tmp_file"

# Replace kitty.conf only if its contents actually changed. Write through a symlink
# instead of replacing it with a regular file via mv.
if ! cmp -s "$config_file" "$tmp_file"; then
    cat "$tmp_file" >"$config_file"
fi

if [[ ! -f "$theme_file" ]]; then
    printf 'Warning: Kitty theme file not found: %s\n' "$theme_file" >&2
fi

# Reload all running Kitty instances.
pkill -USR1 -x kitty >/dev/null 2>&1 || true
