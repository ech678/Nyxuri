#!/usr/bin/env python3
"""Generate the AUR PKGBUILD depends/optdepends arrays from plugin manifests.

Single source of truth (§5.7): adding a plugin only touches plugins/ (its
manifest.toml declares packages); this script regenerates the PKGBUILD's
blocks. Run `python3 packaging/gen-deps.py --update` to rewrite the
generated blocks, or without --update to print them.

T1 single-package policy — the package is a toolbox, not a desktop:

  depends    = ENGINE_DEPENDS (engine runtime only; pacman must not force
               a desktop onto the user)
  optdepends = every plugin's packages (deployable + optional, labeled by
             plugin — `nyxuri on <plugin>` discloses and installs them)
             ∪ CORE_DEPS ∪ AUR_DEPS (session toolchain)
             ∪ ENGINE_OPTDEPENDS (runtime bases the shipped code spawns)

catalog.toml is deliberately absent: it is the `nyxuri deps apps` menu of
recommended install shortcuts, never a package dependency.
"""

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
PKGBUILD = Path(__file__).resolve().parent / "PKGBUILD"

_BEGIN = "# >>> depends (auto-generated by packaging/gen-deps.py) >>>"
_END = "# <<< depends <<<"
_OBEGIN = "# >>> optdepends (auto-generated by packaging/gen-deps.py) >>>"
_OEND = "# <<< optdepends <<<"


# Engine runtime: the whole tree is pure Python + QML + shell scripts —
# nothing else is needed for the package's own code to run. (bash comes with
# the base meta package.)
ENGINE_DEPENDS = ["python"]

# Runtime bases the shipped code directly spawns (optdepends: optional
# functionality degrades with an explicit message when absent).
# key-cli (Clavis upstream system monitor / Spotlight backend) is a known
# gap — see shell/KNOWN-ISSUES.md; register here only after it is brought
# in-repo or formally adopted.
ENGINE_OPTDEPENDS = [
    ("quickshell", "Nyxuri Shell runtime"),
    # 31 shell QML files import Qt5Compat.GraphicalEffects unconditionally and
    # quickshell does not depend on it — a bare quickshell install alone would
    # render the Shell's surfaces without effects. (chroot namcap finding)
    ("qt6-5compat", "Nyxuri Shell visual effects"),
]


def compute_depends(repo_root: Path):
    """Return (depends: list[str], optdepends: list[tuple[pkg, label]]).

    Plugin manifests (deployable AND optional) feed optdepends labeled by
    plugin; CORE_DEPS/AUR_DEPS follow as the session toolchain; ENGINE_*
    constants close the list. First claim wins on package collisions
    (sorted plugin iteration keeps output deterministic).
    """
    sys.path.insert(0, str(repo_root))
    from nyxuri.deploy.manifest import discover_manifest_apps
    from nyxuri.core import AUR_DEPS, CORE_DEPS

    depends = set(ENGINE_DEPENDS)
    optdepends = []
    seen = set()
    for _name, m in sorted(discover_manifest_apps(), key=lambda pair: pair[0]):
        for pkg in list(m.packages_repo) + list(m.packages_aur):
            if pkg not in seen:
                seen.add(pkg)
                optdepends.append((pkg, m.label))
    for pkg in CORE_DEPS:
        if pkg not in seen:
            seen.add(pkg)
            optdepends.append((pkg, "session toolchain"))
    for pkg in AUR_DEPS:
        if pkg not in seen:
            seen.add(pkg)
            optdepends.append((pkg, "session toolchain (AUR)"))
    for pkg, label in ENGINE_OPTDEPENDS:
        if pkg not in seen:
            seen.add(pkg)
            optdepends.append((pkg, label))
    return sorted(depends), optdepends


def _sh_quote(value) -> str:
    return "'" + str(value).replace("'", "'\\''") + "'"


def _render(depends, optdepends):
    dep_block = _BEGIN + "\ndepends=(\n" + "".join(f"  {_sh_quote(p)}\n" for p in depends) + ")\n" + _END
    if optdepends:
        entries = "".join(f"  {_sh_quote(str(p) + ': ' + str(lbl))}\n" for p, lbl in optdepends)
        opt_block = _OBEGIN + "\noptdepends=(\n" + entries + ")\n" + _OEND
    else:
        opt_block = _OBEGIN + "\noptdepends=(\n)\n" + _OEND
    return dep_block + "\n" + opt_block


def update_pkgbuild(depends, optdepends) -> bool:
    """Rewrite the generated blocks in PKGBUILD. Returns True if changed."""
    if not PKGBUILD.is_file():
        return False
    text = PKGBUILD.read_text(encoding="utf-8")
    new = _render(depends, optdepends)
    import re
    pattern = re.compile(re.escape(_BEGIN) + r".*?" + re.escape(_OEND), re.DOTALL)
    if not pattern.search(text):
        return False
    out = pattern.sub(new.rstrip("\n"), text).rstrip("\n") + "\n"
    if out == text:
        return False
    PKGBUILD.write_text(out, encoding="utf-8")
    return True


def main() -> int:
    ap = argparse.ArgumentParser(description="Generate AUR depends from plugin manifests")
    ap.add_argument("--update", action="store_true", help="rewrite PKGBUILD in place")
    args = ap.parse_args()

    depends, optdepends = compute_depends(REPO_ROOT)
    if args.update:
        changed = update_pkgbuild(depends, optdepends)
        print("PKGBUILD " + ("updated" if changed else "unchanged"))
        return 0
    print(_render(depends, optdepends))
    return 0


if __name__ == "__main__":
    sys.exit(main())
